// Offline extraction of text-PCK constants; never changes integrated body spin.
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { solarSystem } from "../src/solar.js";
const source = new URL(
  "../output/surface-originals/pck00011.tpc",
  import.meta.url,
);
const hash = "3dff7b1dbeceaa01f25467767d3fa25816051c85d162d1edf04acb310ee28bb1";
const bytes = await readFile(source);
if (createHash("sha256").update(bytes).digest("hex") !== hash)
  throw new Error("PCK checksum mismatch");
const data = [
  ...bytes.toString().matchAll(/\\begindata([\s\S]*?)(?=\\begintext|$)/g),
]
  .map((m) => m[1])
  .join("\n");
const values = {};
for (const match of data.matchAll(
  /BODY(\d+)_(\w+)\s*=\s*(\([^)]*\)|[^\s]+)/g,
)) {
  values[`${match[1]}_${match[2]}`] = [
    ...match[3].matchAll(/[+-]?(?:\d+\.?\d*|\.\d+)(?:[dDeE][+-]?\d+)?/g),
  ].map((m) => Number(m[0].replace(/[dD]/, "e")));
}
const ids = {
  sun: 10,
  mercury: 199,
  venus: 299,
  earth: 399,
  moon: 301,
  mars: 499,
  phobos: 401,
  deimos: 402,
  jupiter: 599,
  io: 501,
  europa: 502,
  ganymede: 503,
  callisto: 504,
  saturn: 699,
  titan: 606,
  enceladus: 602,
  rhea: 605,
  iapetus: 608,
  uranus: 799,
  ariel: 701,
  umbriel: 702,
  titania: 703,
  oberon: 704,
  miranda: 705,
  neptune: 899,
  triton: 801,
};
const frames = {};
for (const body of solarSystem()) {
  const id = ids[body.id],
    system = Math.floor(id / 100);
  const get = (key) => values[`${id}_${key}`] || [];
  const stride = (values[`${system}_MAX_PHASE_DEGREE`]?.[0] ?? 1) + 1;
  const angles = values[`${system}_NUT_PREC_ANGLES`] || [];
  frames[body.id] = {
    naifId: id,
    referenceRadiusMeters: body.radius,
    canonicalMassKg: body.mass,
    radiiMeters: get("RADII").map((v) => v * 1000),
    ra: get("POLE_RA"),
    dec: get("POLE_DEC"),
    pm: get("PM"),
    raTerms: get("NUT_PREC_RA"),
    decTerms: get("NUT_PREC_DEC"),
    pmTerms: get("NUT_PREC_PM"),
    phases: Array.from({ length: angles.length / stride }, (_, i) =>
      angles.slice(i * stride, (i + 1) * stride),
    ),
  };
  if (!frames[body.id].ra.length || !frames[body.id].pm.length)
    throw new Error(`Missing PCK frame ${body.id}`);
}
await writeFile(
  new URL("../src/surface-pck.js", import.meta.url),
  `// Generated by scripts/prepare-surface-frames.mjs from NASA NAIF pck00011.tpc.\n// Source: https://naif.jpl.nasa.gov/pub/naif/generic_kernels/pck/pck00011.tpc\n// SHA256: ${hash}\nexport const SURFACE_PCK = ${JSON.stringify(frames, null, 2)};\n`,
);
console.log(
  `Prepared ${Object.keys(frames).length} analytic body-fixed frames`,
);
